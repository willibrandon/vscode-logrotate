function validateSource(document, versionDocument, rows) {
  if (document.schemaVersion !== 1 || versionDocument.schemaVersion !== 1) {
    throw new Error("Unsupported language-data schema version.");
  }
  if (!Array.isArray(rows) || rows.length !== 69) {
    throw new Error(`Expected 69 syntax records, received ${rows?.length ?? "none"}.`);
  }
  const actualNames = rows.map(({ name }) => name);
  if (new Set(actualNames).size !== actualNames.length) {
    throw new Error("Directive names must be unique.");
  }
  if (actualNames.filter((name) => name !== "endscript").length !== 68) {
    throw new Error("Expected 68 normal directives plus endscript.");
  }
  const required = [
    "name",
    "category",
    "scopes",
    "arguments",
    "negatedBy",
    "interactions",
    "since",
    "deprecated",
    "ignored",
    "documentation",
    "summary",
    "completion",
    "examples",
  ];
  for (const row of rows) {
    for (const property of required) {
      if (!(property in row)) {
        throw new Error(`${row.name ?? "Unnamed directive"} is missing ${property}.`);
      }
    }
    if (!/^[a-z]+$/.test(row.name)) {
      throw new Error(`Invalid directive name: ${row.name}`);
    }
    if (!versionDocument.supported.some(({ version }) => row.since.startsWith(version))) {
      throw new Error(`${row.name} does not map to a supported version.`);
    }
  }
  if (document.upstreamRevision !== versionDocument.supported[0].upstreamRevision) {
    throw new Error("Directive and version data pin different upstream revisions.");
  }
}

function alternation(values) {
  return `(?:${[...values].sort((left, right) => right.length - left.length || left.localeCompare(right)).join("|")})`;
}

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function escapeMarkdown(value) {
  return value.replaceAll("|", "\\|");
}

async function emit(relativePath, contents) {
  const path = resolve(root, relativePath);
  if (check) {
    let current;
    try {
      current = await readFile(path, "utf8");
    } catch {
      throw new Error(`Generated file is missing: ${relativePath}`);
    }
    if (current !== contents) {
      throw new Error(`Generated file is stale: ${relativePath}`);
    }
    return;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents, "utf8");
}
